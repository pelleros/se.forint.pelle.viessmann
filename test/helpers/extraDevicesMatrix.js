'use strict';

// The extra devices' matrix: for every fixture device, the extra devices pairing lists for it
// (heating circuits, hot water, rooms) and what each gets on the current code: its name and
// data.id, its capabilities in the order it gets them, their options, and its values after a
// shared poll. A compact, diff-friendly golden file next to the capability matrix of the ViCare
// device (which this leaves as it is).
//
// Needs the in-memory Homey fake; call this in the test file before requiring this helper:
//   jest.mock('homey-oauth2app', () => require('<path>/test/helpers/fakeHomeyOAuth2App'));

const path = require('path');

const { extraEntries } = require('../../drivers/vicare/extraPairing');
const { translate } = require('../../lib/errorMessages');
const { loadFixtureDevices } = require('./fixtureDevices');
const {
  APP_VERSION, extraHomey, addExtraDevice, fixtureClient,
} = require('./extraDevices');

const EXTRA_MATRIX_FILE = path.join(__dirname, '../../drivers/vicare/__tests__/extraDevicesMatrix.json');
const KINDS = ['circuit', 'hotWater', 'room'];

// English names, as Homey shows them without a translation
const t = (key, tags) => translate(undefined, key, tags);

/**
 * The extra devices of one fixture device: every fixture counts as a heating device (for
 * circuits and hot water) and as a ViCare Smart Climate device (for rooms), like the capability
 * matrix pairs every fixture as a heating device. The devices share one poll without a ViCare
 * device; after all of them joined, one more poll gives each its values.
 * @param {import('./fixtureDevices').FixtureDevice} fixture
 */
async function fixtureEntry({ features, installations, identity }) {
  const gateway = { installationId: identity.installationId, serial: identity.gatewaySerial };
  const listed = installations.data.flatMap((installation) => installation.gateways || [])
    .flatMap((candidate) => candidate.devices || []).find((device) => String(device.id) === String(identity.deviceId));
  const source = { gateway, device: { id: identity.deviceId, modelId: listed?.modelId, roles: identity.roles } };
  const setup = extraHomey();
  const client = fixtureClient(features);
  const devices = [];
  for (const kind of KINDS) {
    for (const entry of extraEntries(kind, source, features, { t, version: APP_VERSION })) {
      devices.push({ kind, entry, device: await addExtraDevice(setup, kind, entry, client) });
    }
  }
  if (devices.length === 0) return undefined;
  await setup.vicare._devicePollers.get(devices[0].device.getPollingKey()).pollNow();
  const result = {};
  for (const { kind, entry, device } of devices) {
    (result[kind] = result[kind] || []).push({
      name: entry.name,
      id: entry.data.id,
      capabilities: device.getCapabilities(),
      options: Object.fromEntries(device.getCapabilities().map((name) => [name, device.getCapabilityOptions(name)])),
      values: Object.fromEntries(device.getCapabilities().map((name) => [name, device.getCapabilityValue(name)])),
    });
    await device.onOAuth2Deleted();
  }
  return result;
}

/**
 * The whole matrix: per fixture device with extra devices, what they get.
 */
async function buildExtraMatrix() {
  const random = jest.spyOn(Math, 'random').mockReturnValue(0.5); // never the extended poll
  try {
    const devices = {};
    for (const fixture of loadFixtureDevices()) {
      const entry = await fixtureEntry(fixture);
      if (entry) devices[fixture.name] = entry;
    }
    return { devices };
  } finally {
    random.mockRestore();
  }
}

// One extra device per line group, small objects on one line: a change shows up as a few lines
function formatExtraMatrix({ devices }) {
  const json = (value) => JSON.stringify(value);
  const lines = [
    '{',
    '  "_comment": [',
    '    "GENERATED by `npm run matrix` (scripts/updateCapabilityMatrix.js); do not edit by hand.",',
    '    "Per fixture device: the extra devices pairing lists for it (heating circuits, hot water, rooms; every",',
    '    "fixture counts as a heating device and as a ViCare Smart Climate device), with the name and data.id",',
    '    "each gets, its capabilities in order, their options and its values after a shared poll."',
    '  ],',
    '  "devices": {',
    Object.entries(devices).map(([name, kinds]) => [
      `    ${json(name)}: {`,
      Object.entries(kinds).map(([kind, list]) => [
        `      ${json(kind)}: [`,
        list.map((device) => [
          '        {',
          `          "name": ${json(device.name)},`,
          `          "id": ${json(device.id)},`,
          `          "capabilities": ${json(device.capabilities)},`,
          '          "options": {',
          Object.entries(device.options).map(([capability, options]) => `            ${json(capability)}: ${json(options)}`).join(',\n'),
          '          },',
          `          "values": ${json(device.values)}`,
          '        }',
        ].join('\n')).join(',\n'),
        '      ]',
      ].join('\n')).join(',\n'),
      '    }',
    ].join('\n')).join(',\n'),
    '  }',
    '}',
    '',
  ];
  return lines.join('\n');
}

module.exports = { EXTRA_MATRIX_FILE, buildExtraMatrix, formatExtraMatrix };
